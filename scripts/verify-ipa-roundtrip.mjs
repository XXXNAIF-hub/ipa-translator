/**
 * Parse fixtures/sample.ipa → translate → build IPA blob with ar.lproj/Localizable.strings
 * containing Arabic. Uses JSZip + the same engine cascade as the app.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import JSZip from "jszip";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const ipaPath = join(root, "fixtures", "sample.ipa");
const outDir = join(root, ".cache");
const ARABIC = /[\u0600-\u06FF]/;

const TE_LIB_KEY = "AIzaSyATBXajvzQLTDHEQbcpq0Ihe0vWDHmO520";

async function translatePa(texts) {
  const res = await fetch(
    "https://translate-pa.googleapis.com/v1/translateHtml",
    {
      method: "POST",
      headers: {
        "Content-Type": "application/json+protobuf",
        "X-Goog-API-Key": TE_LIB_KEY,
      },
      body: JSON.stringify([[texts, "en", "ar"], "te_lib"]),
    }
  );
  if (!res.ok) throw new Error(`pa ${res.status}`);
  const data = await res.json();
  return Array.isArray(data?.[0]) ? data[0] : data;
}

async function translateCascade(text) {
  try {
    const [out] = await translatePa([text]);
    if (ARABIC.test(out)) return out;
  } catch {
    /* fall through */
  }
  try {
    const url = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(text)}&langpair=en|ar`;
    const res = await fetch(url);
    const data = await res.json();
    const out = data?.responseData?.translatedText || "";
    if (ARABIC.test(out) && !/MYMEMORY WARNING/i.test(out)) return out;
  } catch {
    /* fall through */
  }
  try {
    const res = await fetch("https://libretranslate.com/translate", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        q: text,
        source: "en",
        target: "ar",
        format: "text",
      }),
    });
    const data = await res.json();
    if (ARABIC.test(data.translatedText || "")) return data.translatedText;
  } catch {
    /* fall through */
  }
  throw new Error(`no engine translated: ${text}`);
}

function parseStrings(content) {
  const pairs = [];
  const re = /"((?:\\.|[^"\\])*)"\s*=\s*"((?:\\.|[^"\\])*)"\s*;/g;
  let m;
  while ((m = re.exec(content)) !== null) {
    pairs.push({ key: m[1], value: m[2] });
  }
  return pairs;
}

function serialize(entries) {
  const esc = (s) =>
    s
      .replace(/\\/g, "\\\\")
      .replace(/"/g, '\\"')
      .replace(/\n/g, "\\n");
  return (
    "/* Generated by verify-ipa-roundtrip */\n\n" +
    entries.map((e) => `"${esc(e.key)}" = "${esc(e.value)}";`).join("\n") +
    "\n"
  );
}

const buf = readFileSync(ipaPath);
const zip = await JSZip.loadAsync(buf);

const enEntry = zip.file("Payload/SampleApp.app/en.lproj/Localizable.strings");
if (!enEntry) throw new Error("fixture missing en Localizable.strings");
const enText = await enEntry.async("string");
const pairs = parseStrings(enText);
console.log(`Parsed ${pairs.length} strings from fixture`);

const skip = new Set(["support_email", "website_url", "bundle_hint"]);
const translated = [];
for (const p of pairs) {
  if (skip.has(p.key) || /@|https?:|\.com/.test(p.value)) {
    translated.push({ key: p.key, value: p.value, skipped: true });
    continue;
  }
  const ar = await translateCascade(p.value);
  console.log(`  ${JSON.stringify(p.value)} → ${JSON.stringify(ar)}`);
  translated.push({ key: p.key, value: ar });
}

const outZip = new JSZip();
const copyJobs = [];
zip.forEach((path, file) => {
  if (file.dir) {
    outZip.folder(path);
    return;
  }
  copyJobs.push(
    file.async("uint8array").then((data) => {
      outZip.file(path, data, { binary: true });
    })
  );
});
await Promise.all(copyJobs);

const arPath = "Payload/SampleApp.app/ar.lproj/Localizable.strings";
const arContent = serialize(
  translated.map(({ key, value }) => ({ key, value }))
);
outZip.file(arPath, arContent);

const outBuf = await outZip.generateAsync({
  type: "nodebuffer",
  compression: "DEFLATE",
});
mkdirSync(outDir, { recursive: true });
const outIpa = join(outDir, "sample-ar-translated.ipa");
writeFileSync(outIpa, outBuf);
console.log(`Wrote ${outIpa} (${outBuf.length} bytes)`);

// Verify Arabic inside
const check = await JSZip.loadAsync(outBuf);
const arFile = check.file(arPath);
if (!arFile) {
  console.error(`FAIL: missing ${arPath}`);
  process.exit(1);
}
const arText = await arFile.async("string");
if (!ARABIC.test(arText)) {
  console.error("FAIL: ar.lproj/Localizable.strings has no Arabic");
  process.exit(1);
}
if (!arText.includes("login_button") && !/"Sign In"|تسجيل/.test(arText)) {
  console.log("(note) keys present check loose");
}
console.log(`OK: ${arPath} contains Arabic`);
console.log("--- ar.lproj preview ---");
console.log(arText.slice(0, 600));
console.log("PASS roundtrip");
